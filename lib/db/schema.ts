/**
 * Database schema - plan section 4.
 *
 * Every user-owned table carries `user_id` even where it could be derived by
 * joining upwards. The app has one user today; carrying the column from day one
 * means every query can filter on it directly and multi-user needs no migration.
 *
 * Band scores are numeric(2,1) so half bands (6.5) round-trip exactly.
 */
import {
  check,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { relations, sql } from "drizzle-orm";

/**
 * Specific enough to count. Phase 4's repeated-mistake analysis needs to know
 * a learner keeps dropping articles, which "grammar" would never tell it.
 * Mirrors MISTAKE_CATEGORIES in lib/schemas.ts - keep the two in step.
 */
export const mistakeCategory = pgEnum("mistake_category", [
  "article",
  "preposition",
  "countability",
  "agreement",
  "tense",
  "word_choice",
  "collocation",
  "repetition",
  "fluency",
  "other",
]);

/** How far the audio supports the pronunciation indicator. */
export const pronunciationConfidence = pgEnum("pronunciation_confidence", [
  "high",
  "medium",
  "low",
  "unavailable",
]);

/** Window kinds for the atomic rate counters. */
export const rateWindow = pgEnum("rate_window", ["day", "minute"]);

/** Routes that consume Gemini quota and are therefore counted against the cap. */
export const apiRoute = pgEnum("api_route", [
  "question",
  "evaluate",
  "model_answer",
]);

export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    email: text("email").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [uniqueIndex("users_email_lower_idx").on(sql`lower(${t.email})`)],
);

/** One examiner session = one attempt at Part 1, 2 or 3. */
export const sessions = pgTable(
  "sessions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    part: smallint("part").notNull(),
    topic: text("topic"),
    startedAt: timestamp("started_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    check("sessions_part_valid", sql`${t.part} between 1 and 3`),
    index("sessions_user_started_idx").on(t.userId, t.startedAt),
    /** Phase 4: progress filtered to one part. */
    index("sessions_user_part_idx").on(t.userId, t.part),
  ],
);

/** One question and the transcript of the spoken answer. Audio is never stored. */
export const answers = pgTable(
  "answers",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    sessionId: uuid("session_id")
      .notNull()
      .references(() => sessions.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    question: text("question").notNull(),
    transcript: text("transcript").notNull(),
    durationSec: integer("duration_sec"),
    wordCount: integer("word_count"),
    /**
     * Idempotency key, generated by the browser once per recording.
     *
     * A double tap, a retry after a timeout, or a reconnecting phone can all
     * send the same recording twice. The unique index below makes the second
     * write lose, and /api/evaluate returns the first result instead of
     * marking the answer again - which also stops a retry double-counting the
     * daily cap.
     */
    clientToken: text("client_token"),
    /**
     * Set when this answer is a second go at the same question.
     *
     * Always points at the ORIGINAL attempt, never at another retry, so a
     * chain of attempts is a flat set rather than a linked list - which keeps
     * "exclude retries" a single `is null` test instead of a recursive walk.
     * `lib/db/queries.ts` resolves a retry-of-a-retry back to its root before
     * inserting.
     *
     * Retries are excluded from the progress baseline and moving average:
     * a second attempt at a question you have already seen and been marked on
     * is not comparable to a cold answer, and letting it into the trend would
     * flatter it.
     */
    retryOfAnswerId: uuid("retry_of_answer_id"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("answers_session_idx").on(t.sessionId),
    index("answers_user_created_idx").on(t.userId, t.createdAt),
    uniqueIndex("answers_user_client_token_idx")
      .on(t.userId, t.clientToken)
      .where(sql`${t.clientToken} is not null`),
    foreignKey({
      columns: [t.retryOfAnswerId],
      foreignColumns: [t.id],
      name: "answers_retry_of_answer_id_answers_id_fk",
    }).onDelete("set null"),
    index("answers_retry_of_idx")
      .on(t.retryOfAnswerId)
      .where(sql`${t.retryOfAnswerId} is not null`),
  ],
);

/**
 * Scored feedback for one answer.
 *
 * `pronunciationEst` is an indicator only and must never be shown as an
 * official band. It is nullable because an answer with no usable audio gets an
 * honest null rather than a guess.
 *
 * `overall` is computed in lib/scoring.ts, not returned by the model.
 *
 * `promptVersion` and `model` record what produced the scores, so a band given
 * today stays interpretable after the prompt changes. `evidence` keeps the
 * per-criterion quotes that justified each band.
 *
 * `rawJson` keeps the validated model output so the display can change without
 * re-evaluating.
 */
export const feedback = pgTable(
  "feedback",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    answerId: uuid("answer_id")
      .notNull()
      .references(() => answers.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    fluency: numeric("fluency", { precision: 2, scale: 1 }).notNull(),
    lexical: numeric("lexical", { precision: 2, scale: 1 }).notNull(),
    grammar: numeric("grammar", { precision: 2, scale: 1 }).notNull(),
    pronunciationEst: numeric("pronunciation_est", {
      precision: 2,
      scale: 1,
    }),
    pronunciationConfidence: pronunciationConfidence(
      "pronunciation_confidence",
    ).notNull(),
    overall: numeric("overall", { precision: 2, scale: 1 }).notNull(),
    strengths: jsonb("strengths").$type<string[]>().notNull().default([]),
    nextSteps: jsonb("next_steps").$type<string[]>().notNull().default([]),
    /** Per-criterion quotes from the transcript that justified each band. */
    evidence: jsonb("evidence")
      .$type<Record<string, string[]>>()
      .notNull()
      .default({}),
    /** Deterministic caps that were applied, e.g. a Part 2 under a minute. */
    guardrails: jsonb("guardrails")
      .$type<Array<{ code: string; message: string }>>()
      .notNull()
      .default([]),
    promptVersion: text("prompt_version").notNull(),
    model: text("model").notNull(),
    rawJson: jsonb("raw_json").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    uniqueIndex("feedback_answer_idx").on(t.answerId),
    index("feedback_user_created_idx").on(t.userId, t.createdAt),
  ],
);

/** One specific mistake with its correction. Drives repeated-mistake analysis. */
export const mistakes = pgTable(
  "mistakes",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    answerId: uuid("answer_id")
      .notNull()
      .references(() => answers.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    category: mistakeCategory("category").notNull(),
    original: text("original").notNull(),
    correction: text("correction").notNull(),
    explanation: text("explanation"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("mistakes_answer_idx").on(t.answerId),
    index("mistakes_user_category_idx").on(t.userId, t.category),
    /** Phase 4: the last-7-days vs previous-7-days repeated-mistake windows. */
    index("mistakes_user_created_idx").on(t.userId, t.createdAt),
    /**
     * Phase 4 groups repeated mistakes by the CASE-FOLDED, TRIMMED pair, so
     * the index has to match that expression. An index on the raw columns
     * (which is what phase 4 shipped) cannot serve
     * `group by lower(btrim(original)), lower(btrim(correction))` at all.
     */
    index("mistakes_user_pair_folded_idx").on(
      t.userId,
      sql`lower(btrim(${t.original}))`,
      sql`lower(btrim(${t.correction}))`,
    ),
  ],
);

export const vocabNotebook = pgTable(
  "vocab_notebook",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    phrase: text("phrase").notNull(),
    meaning: text("meaning"),
    example: text("example"),
    /** Null when added by hand rather than captured from an answer. */
    sourceAnswerId: uuid("source_answer_id").references(() => answers.id, {
      onDelete: "set null",
    }),
    /**
     * Review scheduling, phase 4. Deliberately a fixed ladder rather than a
     * real spaced-repetition algorithm: 1, 3, 7 then 14 days, reset to the
     * start on "again". `intervalDays` is the step that produced the current
     * `nextReview`, which is what lets the next step be chosen without
     * storing a history.
     */
    nextReview: timestamp("next_review", { withTimezone: true }),
    intervalDays: integer("interval_days").notNull().default(0),
    reviewCount: integer("review_count").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("vocab_user_created_idx").on(t.userId, t.createdAt),
    /** Drives "what is due today" without scanning the notebook. */
    index("vocab_user_next_review_idx").on(t.userId, t.nextReview),
  ],
);

/**
 * One row per Gemini-backed request, written before the call so that failed
 * calls still count - they cost quota too. The daily cap is counted from here
 * rather than from `answers`, which only records successful evaluations.
 */
export const apiRequests = pgTable(
  "api_requests",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    route: apiRoute("route").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [index("api_requests_user_created_idx").on(t.userId, t.createdAt)],
);

/**
 * Atomic request counters.
 *
 * The phase 2 cap counted rows in `api_requests` with a SELECT and then
 * inserted, which two parallel requests could both pass. This table is
 * incremented with a single `insert ... on conflict do update ... where
 * used < cap` statement: the conflicting row is locked, the WHERE is
 * re-evaluated against the locked row, and a request over the limit gets no
 * row back. That makes the cap exact under concurrency.
 *
 * `api_requests` is kept as an audit log of which route spent what.
 */
export const rateBuckets = pgTable(
  "rate_buckets",
  {
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    kind: rateWindow("kind").notNull(),
    /** Start of the window: a UTC day, or a clock minute. */
    bucketStart: timestamp("bucket_start", { withTimezone: true }).notNull(),
    used: integer("used").notNull().default(0),
  },
  (t) => [
    primaryKey({ columns: [t.userId, t.kind, t.bucketStart] }),
    index("rate_buckets_started_idx").on(t.bucketStart),
  ],
);

export const usersRelations = relations(users, ({ many }) => ({
  sessions: many(sessions),
  answers: many(answers),
  vocab: many(vocabNotebook),
}));

export const sessionsRelations = relations(sessions, ({ one, many }) => ({
  user: one(users, { fields: [sessions.userId], references: [users.id] }),
  answers: many(answers),
}));

export const answersRelations = relations(answers, ({ one, many }) => ({
  session: one(sessions, {
    fields: [answers.sessionId],
    references: [sessions.id],
  }),
  user: one(users, { fields: [answers.userId], references: [users.id] }),
  feedback: one(feedback),
  mistakes: many(mistakes),
}));

export const feedbackRelations = relations(feedback, ({ one }) => ({
  answer: one(answers, {
    fields: [feedback.answerId],
    references: [answers.id],
  }),
  user: one(users, { fields: [feedback.userId], references: [users.id] }),
}));

export const mistakesRelations = relations(mistakes, ({ one }) => ({
  answer: one(answers, {
    fields: [mistakes.answerId],
    references: [answers.id],
  }),
  user: one(users, { fields: [mistakes.userId], references: [users.id] }),
}));

export const vocabNotebookRelations = relations(vocabNotebook, ({ one }) => ({
  user: one(users, { fields: [vocabNotebook.userId], references: [users.id] }),
  sourceAnswer: one(answers, {
    fields: [vocabNotebook.sourceAnswerId],
    references: [answers.id],
  }),
}));
